function buildPortCells(items: Endpoint[]): PortCell[] {
  const usedPorts = new Map<number, PortCell>();
  for (const ep of items) {
    if (ep.protocol !== "tcp") continue;
    const existing = usedPorts.get(ep.port);
    if (existing) {
      existing.state = "used";
      existing.service = `${existing.service} / ${ep.service}`;
      continue;
    }
    usedPorts.set(ep.port, {
      port: ep.port,
      protocol: "tcp",
      state: ep.source === "INFERRED" ? "inferred" : ep.hidden ? "hidden" : "used",
      service: ep.service,
      endpointId: ep.id,
    });
  }
  return Array.from({ length: 2048 }, (_, index) => {
    const port = index + 1;
    return usedPorts.get(port) ?? { port, protocol: "tcp", state: "free" };
  });
}

function buildUdpPorts(items: Endpoint[]): PortCell[] {
  return items
    .filter(
      (endpoint) =>
        endpoint.protocol === "udp" &&
        endpoint.status === "running" &&
        (endpoint.scope === "HOST" || endpoint.scope === "LAN" || endpoint.scope === "HOST_NET" || endpoint.scope === "LOOPBACK"),
    )
    .map((endpoint) => ({
      port: endpoint.port,
      protocol: "udp" as const,
      state: endpoint.source === "INFERRED" ? ("inferred" as const) : endpoint.hidden ? ("hidden" as const) : ("used" as const),
      service: endpoint.service,
      endpointId: endpoint.id,
    }));
}

export let portCells: PortCell[] = buildPortCells(endpoints);

export let udpPorts: PortCell[] = buildUdpPorts(endpoints);

export let quickAccess = endpoints.filter((endpoint) => endpoint.favorite && !endpoint.hidden);


export interface SnapshotPayload {
  host?: { preferredIp?: string };
  containers?: ContainerInfo[];
  networks?: NetworkInfo[];
  endpoints?: Endpoint[];
}

export interface OverviewPayload {
  counts?: Partial<OverviewStats>;
  recent?: RecentEvent[];
  favorites?: Endpoint[];
}

export function applySnapshot(snapshot: SnapshotPayload): boolean {
  if (!snapshot || !Array.isArray(snapshot.endpoints)) {
    return false;
  }
  endpoints = snapshot.endpoints;
  if (Array.isArray(snapshot.containers)) containers = snapshot.containers;
  if (Array.isArray(snapshot.networks)) networks = snapshot.networks;
  portCells = buildPortCells(endpoints);
  udpPorts = buildUdpPorts(endpoints);
  quickAccess = endpoints.filter((endpoint) => endpoint.favorite && !endpoint.hidden);
  return true;
}

export function applyOverview(overview: OverviewPayload): void {
  if (overview.counts) {
    overviewStats = { ...overviewStats, ...overview.counts };
  }
  if (Array.isArray(overview.recent)) {
    recentEvents = overview.recent;
  }
  if (Array.isArray(overview.favorites)) {
    quickAccess = overview.favorites.filter((endpoint) => !endpoint.hidden);
  }
}
